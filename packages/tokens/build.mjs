// Builds every platform's tokens from src/*.json (the W3C design tokens format, DTCG) with
// Style Dictionary:
//
//   dist/tokens.css                    CSS custom properties: light on :root, dark on
//                                      [data-theme="dark"] and prefers-color-scheme: dark
//   dist/theme.css                     Tailwind v4 @theme, mapping utilities to those
//                                      properties (bg-surface, text-muted, rounded-xl, ...)
//   dist/tokens.ts                     the same values for TypeScript
//   ../../apps/cli/src/myapp/theme.json  the terminal UI's Textual themes
//
// `node build.mjs --check` builds in memory and fails if a committed file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import StyleDictionary from "style-dictionary";

const here = dirname(fileURLToPath(import.meta.url));
const SHARED = ["palette", "typography", "space", "size", "shape"].map((f) =>
  join(here, "src", `${f}.json`),
);
const HEADER =
  "Generated by packages/tokens/build.mjs from packages/tokens/src. Don't edit.";
const PREFIX = "ds";

// Style Dictionary's CSS transforms handle the older "time" type, not DTCG "duration".
StyleDictionary.registerTransform({
  name: "duration/css",
  type: "value",
  filter: (token) => token.$type === "duration",
  transform: (token) => `${token.$value.value}${token.$value.unit}`,
});

async function tokensFor(theme) {
  const sd = new StyleDictionary({
    source: [...SHARED, join(here, "src", `color.${theme}.json`)],
    usesDtcg: true,
    log: { verbosity: "silent", warnings: "disabled" },
    platforms: {
      css: {
        transforms: [
          ...StyleDictionary.hooks.transformGroups.css,
          "duration/css",
        ],
        prefix: PREFIX,
      },
    },
  });
  return (await sd.getPlatformTokens("css")).allTokens;
}

const light = await tokensFor("light");
const dark = await tokensFor("dark");
const isColor = (t) => t.path[0] === "color";
const isPublic = (t) => t.path[0] !== "palette"; // components never reach for raw colors
const cssVar = (t) => `--${t.name}`;
const declarations = (tokens) =>
  tokens.map((t) => `  ${cssVar(t)}: ${t.$value};`).join("\n");

// --- dist/tokens.css
const tokensCss = `/* ${HEADER} */

:root {
${declarations(light.filter(isPublic))}
  color-scheme: light;
}

:root[data-theme="dark"] {
${declarations(dark.filter(isColor))}
  color-scheme: dark;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${declarations(dark.filter(isColor)).replaceAll("\n  ", "\n    ").replace(/^ {2}/, "    ")}
    color-scheme: dark;
  }
}
`;

// --- dist/theme.css: Tailwind's own theme namespaces, pointed at the custom properties.
const byPath = (prefix) =>
  light.filter((t) => t.path.join(".").startsWith(prefix));
const key = (t, from) => t.path.slice(from).join("-");
// Every Tailwind namespace the tokens own is cleared first, so a utility outside the tokens
// (font-bold, leading-tight, max-w-7xl, drop-shadow-lg) generates no CSS at all. Breakpoints,
// animations (animate-spin) and aspect ratios stay Tailwind's own.
const CLEARED = [
  "color",
  "font",
  "font-weight",
  "text",
  "tracking",
  "leading",
  "radius",
  "shadow",
  "inset-shadow",
  "drop-shadow",
  "text-shadow",
  "blur",
  "container",
  "ease",
];
const tailwind = [
  ...CLEARED.map((ns) => `  --${ns}-*: initial;`),
  ...byPath("color.").map((t) => `  --color-${key(t, 1)}: var(${cssVar(t)});`),
  ...byPath("font.family.").map(
    (t) => `  --font-${key(t, 2)}: var(${cssVar(t)});`,
  ),
  ...byPath("font.size.").flatMap((t) => [
    `  --text-${key(t, 2)}: var(${cssVar(t)});`,
    `  --text-${key(t, 2)}--line-height: var(--${PREFIX}-font-line-height-${key(t, 2)});`,
  ]),
  ...byPath("font.weight.").map(
    (t) => `  --font-weight-${key(t, 2)}: var(${cssVar(t)});`,
  ),
  ...byPath("font.tracking.").map(
    (t) => `  --tracking-${key(t, 2)}: var(${cssVar(t)});`,
  ),
  `  --spacing: var(--${PREFIX}-space-unit);`,
  ...byPath("radius.").map(
    (t) => `  --radius-${key(t, 1)}: var(${cssVar(t)});`,
  ),
  ...byPath("shadow.").map(
    (t) => `  --shadow-${key(t, 1)}: var(${cssVar(t)});`,
  ),
  ...byPath("size.container.").map(
    (t) => `  --container-${key(t, 2)}: var(${cssVar(t)});`,
  ),
  ...byPath("motion.easing.").map(
    (t) => `  --ease-${key(t, 2)}: var(${cssVar(t)});`,
  ),
  // What a bare `transition-colors` uses.
  `  --default-transition-duration: var(--${PREFIX}-motion-duration-fast);`,
  `  --default-transition-timing-function: var(--${PREFIX}-motion-easing-standard);`,
];
const themeCss = `/* ${HEADER}
   Tailwind v4 theme: only the design system's values exist as utilities. Tailwind's own
   colors, fonts, weights, sizes, line heights, tracking, radii, shadows, blurs, content
   widths and easings are cleared, so components can't drift from the tokens. */

@theme inline {
${tailwind.join("\n")}
}
`;

// --- dist/tokens.ts: resolved values, nested like the source.
function nest(tokens) {
  const out = {};
  for (const t of tokens) {
    let node = out;
    for (const part of t.path.slice(0, -1)) node = node[part] ??= {};
    node[t.path.at(-1)] = t.$value;
  }
  return out;
}
const shared = nest(light.filter((t) => isPublic(t) && !isColor(t)));
const tokensTs = `// ${HEADER}

export const tokens = ${JSON.stringify(
  {
    ...shared,
    color: {
      light: nest(light.filter(isColor)).color,
      dark: nest(dark.filter(isColor)).color,
    },
  },
  null,
  2,
)} as const;

export type Tokens = typeof tokens;
`;

// --- the terminal UI's themes: Textual's Theme fields, from the semantic colors.
const color = (tokens, name) =>
  tokens.find((t) => t.path.join(".") === `color.${name}`).$value;
const textual = (tokens, dark) => ({
  primary: color(tokens, "accent"),
  secondary: color(tokens, "text-muted"),
  accent: color(tokens, "accent"),
  foreground: color(tokens, "text"),
  background: color(tokens, "bg"),
  surface: color(tokens, "surface"),
  panel: color(tokens, "surface-muted"),
  success: color(tokens, "success"),
  warning: color(tokens, "warning"),
  error: color(tokens, "danger"),
  dark,
});
const textualJson = `${JSON.stringify({ _comment: HEADER, light: textual(light, false), dark: textual(dark, true) }, null, 2)}\n`;

const outputs = {
  [join(here, "dist", "tokens.css")]: tokensCss,
  [join(here, "dist", "theme.css")]: themeCss,
  [join(here, "dist", "tokens.ts")]: tokensTs,
  [join(here, "..", "..", "apps", "cli", "src", "myapp", "theme.json")]:
    textualJson,
};

if (process.argv.includes("--check")) {
  const stale = Object.entries(outputs).filter(([path, text]) => {
    try {
      return readFileSync(path, "utf8") !== text;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(
      `Out of date: ${stale.map(([p]) => p.replace(`${join(here, "..", "..")}/`, "")).join(", ")}`,
    );
    console.error("Run `pnpm tokens:build` and commit the result.");
    process.exit(1);
  }
  console.log("Tokens are up to date.");
} else {
  for (const [path, text] of Object.entries(outputs)) writeFileSync(path, text);
  console.log(`Wrote ${Object.keys(outputs).length} files.`);
}
